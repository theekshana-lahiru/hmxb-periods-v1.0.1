"""Check that the input files in HMXB_DATA are exactly those used for the paper.

    python data/verify_inputs.py [path-to-data-folder]

The data folder contains Stars/ (one sub-folder per source) and HMXBwebcat_latest.xlsx. Every file
listed in the three manifests is looked up and its SHA-256 checksum compared with the manifest.
The BAT transient-monitor light curves are regenerated by the BAT team as new data arrive, so files
downloaded today differ from those used here (FITS DATE 2026-02-01); the data snapshot
(data/make_data_snapshot.py) preserves the exact versions."""
import csv
import hashlib
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def sha256(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for b in iter(lambda: fh.read(chunk), b""):
            h.update(b)
    return h.hexdigest()


def main(argv):
    root = Path(argv[0]) if argv else Path(os.environ.get("HMXB_DATA", r"D:\HMXBs"))
    n_ok = n_bad = n_missing = 0
    for man, base in (("manifest_bat_lightcurves.csv", root / "Stars"),
                      ("manifest_xmm_pps_lightcurves.csv", root / "Stars"),
                      ("manifest_catalogue.csv", root)):
        with open(HERE / man, newline="", encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                p = base / row["file"]
                if not p.exists():
                    n_missing += 1
                    print("missing  ", p)
                elif sha256(p) != row["sha256"]:
                    n_bad += 1
                    print("different", p)
                else:
                    n_ok += 1
    print(f"{n_ok} identical, {n_bad} different, {n_missing} missing")
    return 0 if (n_bad == 0 and n_missing == 0) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
